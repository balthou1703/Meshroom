"""
A head generated by an AI model (TRELLIS.2) for the FaceBuilder, and the FaceBuilder head registered on it.

    generate: a photo of the head (cut out) -> a textured mesh (TRELLIS.2, in its own Python: trellis2Runner.py);
    findLandmarks: the MediaPipe landmarks of its face, found on renders of it (whatever its orientation), in 3D;
    alignment: the similarity putting it on the face of the FaceBuilder (in the space of the head, like the face);
    registerHead: the head of the FaceBuilder (MediaPipe face, ICT ears, skull, neck) warped onto it: its face on the
        landmarks found on it, its proportions (identity modes) and ears on its surface (closest points), the ears
        then refined on their own.
"""
import os
import subprocess
from typing import Optional, Tuple

import numpy as np

from . import face, scene3d


class AIHeadUnavailable(RuntimeError):
    pass


# Generation

# The generators: their runner script, the environment variables of their Python and of their clone
MODELS = {
    "triposr": {"runner": "triposrRunner.py", "python": "MESHROOM_TRIPOSR_PYTHON", "root": "MESHROOM_TRIPOSR_ROOT",
                "label": "TripoSR"},
    "trellis2": {"runner": "trellis2Runner.py", "python": "MESHROOM_TRELLIS2_PYTHON", "root": "MESHROOM_TRELLIS2_ROOT",
                 "label": "TRELLIS.2"},
}


def runnerPath(model: str = "trellis2") -> str:
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), "neural", MODELS[model]["runner"])


def runnerEnvironment(python: str) -> dict:
    """ The environment variables of the Python of a generator: not the Python of Meshroom (rez: PYTHONPATH, PYTHONHOME), the
    libraries of its environment first (CUDA of the toolkit installed with it: setupTrellis2.sh). """
    environment = dict(os.environ)
    for name in ("PYTHONPATH", "PYTHONHOME", "PYTHONSTARTUP"):
        environment.pop(name, None)
    prefix = os.path.dirname(os.path.dirname(os.path.abspath(python)))
    library = os.path.join(prefix, "lib")
    if os.path.isdir(library):
        environment["LD_LIBRARY_PATH"] = library + (os.pathsep + environment["LD_LIBRARY_PATH"]
                                                    if environment.get("LD_LIBRARY_PATH") else "")
    environment["PATH"] = os.path.join(prefix, "bin") + os.pathsep + environment.get("PATH", "")
    environment.setdefault("CUDA_HOME", prefix)
    return environment


def generate(rgba: np.ndarray, output: str, model: str = "triposr", python: Optional[str] = None,
             root: Optional[str] = None, cancel=None, log=None) -> str:
    """
    A head generated from an image (h, w, 4) float in [0, 1] (alpha: the person) by `model` (MODELS), written to
    `output` (.npz). Its runner runs in another process: TripoSR in Meshroom's own Python (or MESHROOM_TRIPOSR_PYTHON),
    TRELLIS.2 in the Python of its environment (MESHROOM_TRELLIS2_PYTHON, without Meshroom's packages); `root`: the
    clone of its repository (MESHROOM_TRIPOSR_ROOT, MESHROOM_TRELLIS2_ROOT).
    """
    import sys
    from .headFit import writePngRGBA
    if model not in MODELS:
        raise AIHeadUnavailable(f"AI head: unknown model {model!r}")
    spec = MODELS[model]
    python = python or os.environ.get(spec["python"])
    root = root or os.environ.get(spec["root"], "")
    if model == "trellis2" and not python:
        raise AIHeadUnavailable("TRELLIS.2 is not set up: set MESHROOM_TRELLIS2_PYTHON to the python of its environment "
                                "(and MESHROOM_TRELLIS2_ROOT to its clone); see docs/live-compositing.md.")
    if model == "trellis2" and not root:
        raise AIHeadUnavailable(f"{spec['label']} is not set up: set {spec['root']} to the clone of its repository; see "
                                "docs/live-compositing.md.")
    os.makedirs(os.path.dirname(os.path.abspath(output)), exist_ok=True)
    imagePath = os.path.splitext(output)[0] + "_input.png"
    writePngRGBA(imagePath, (np.clip(rgba, 0, 1) * 255).astype(np.uint8))
    command = [python or sys.executable, runnerPath(model), imagePath, output] + (["--root", root] if root else [])
    # Meshroom's own Python keeps its environment (its packages); another one gets its own
    environment = runnerEnvironment(python) if python else dict(os.environ)
    process = subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, env=environment)
    lines = []
    try:
        for line in process.stdout:
            lines.append(line.rstrip())
            if log:
                log(line.rstrip())
            if cancel:
                cancel()
    except BaseException:
        process.kill()
        raise
    if process.wait() != 0 or not os.path.exists(output):
        tail = "\n".join(lines[-15:])
        raise AIHeadUnavailable(f"{spec['label']} failed (exit code {process.returncode}):\n{tail}")
    return output


def loadMesh(path: str) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """ (vertices (n, 3), triangles (m, 3), colors (n, 3) in [0, 1]) of a generated head (.npz), a .glb or an .obj. """
    if not path or not os.path.exists(path):
        raise AIHeadUnavailable(f"AI head: no file {path!r}")
    if path.lower().endswith(".npz"):
        data = np.load(path)
        vertices = np.asarray(data["vertices"], dtype=np.float64)
        triangles = np.asarray(data["faces"], dtype=np.int64)
        colors = np.asarray(data["colors"], dtype=np.float64) / 255.0 if "colors" in data else \
            np.full((len(vertices), 3), 0.7)
        return vertices, triangles, colors
    if path.lower().endswith(".obj"):
        vertices, faces = [], []
        with open(path) as f:
            for line in f:
                parts = line.split()
                if not parts:
                    continue
                if parts[0] == "v":
                    vertices.append([float(v) for v in parts[1:4]])
                elif parts[0] == "f":
                    ids = [int(p.split("/")[0]) for p in parts[1:]]
                    ids = [i - 1 if i > 0 else len(vertices) + i for i in ids]
                    faces += [[ids[0], ids[i], ids[i + 1]] for i in range(1, len(ids) - 1)]
        vertices = np.array(vertices, dtype=np.float64).reshape(-1, 3)
        return vertices, np.array(faces, dtype=np.int64).reshape(-1, 3), np.full((len(vertices), 3), 0.7)
    if path.lower().endswith(".glb"):
        return readGlb(path)
    raise AIHeadUnavailable(f"AI head: {path!r} is not a .npz (Generate AI Head), a .glb or an .obj")


_GLB_TYPES = {5120: np.int8, 5121: np.uint8, 5122: np.int16, 5123: np.uint16, 5125: np.uint32, 5126: np.float32}
_GLB_SIZES = {"SCALAR": 1, "VEC2": 2, "VEC3": 3, "VEC4": 4}


def readGlb(path: str) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    (vertices, triangles, colors in [0, 1]) of a binary glTF (.glb: what TRELLIS.2 and most image-to-3D services
    export): its triangle primitives together, the color of each vertex from its COLOR_0 or its base color texture at
    its UV (PIL to decode it; gray without). Node transforms are ignored (the head is placed on the face afterwards).
    """
    import json
    import struct
    with open(path, "rb") as f:
        data = f.read()
    magic, _, _ = struct.unpack_from("<4sII", data, 0)
    if magic != b"glTF":
        raise AIHeadUnavailable(f"AI head: {path!r} is not a binary glTF")
    offset, document, binary = 12, None, b""
    while offset < len(data):
        length, kind = struct.unpack_from("<I4s", data, offset)
        chunk = data[offset + 8:offset + 8 + length]
        if kind == b"JSON":
            document = json.loads(chunk.decode("utf-8"))
        elif kind == b"BIN\x00":
            binary = chunk
        offset += 8 + length
    if document is None:
        raise AIHeadUnavailable(f"AI head: {path!r} has no glTF document")

    def view(index):
        bufferView = document["bufferViews"][index]
        start = bufferView.get("byteOffset", 0)
        return binary[start:start + bufferView["byteLength"]], bufferView.get("byteStride")

    def accessor(index):
        item = document["accessors"][index]
        raw, stride = view(item["bufferView"])
        dtype = np.dtype(_GLB_TYPES[item["componentType"]])
        size = _GLB_SIZES[item["type"]]
        start = item.get("byteOffset", 0)
        count = item["count"]
        if stride and stride != size * dtype.itemsize:
            rows = np.frombuffer(raw, np.uint8, count=stride * (count - 1) + size * dtype.itemsize, offset=start)
            values = np.lib.stride_tricks.as_strided(rows, (count, size * dtype.itemsize), (stride, 1)).copy()
            values = values.view(dtype).reshape(count, size)
        else:
            values = np.frombuffer(raw, dtype, count=count * size, offset=start).reshape(count, size)
        values = values.astype(np.float64)
        if item.get("normalized") and dtype.kind in "iu":
            values /= float(np.iinfo(dtype).max)
        return values

    def texture(material):
        info = (material or {}).get("pbrMetallicRoughness", {}).get("baseColorTexture")
        if info is None:
            return None
        source = document["textures"][info["index"]]
        image = source.get("source", source.get("extensions", {}).get("EXT_texture_webp", {}).get("source"))
        if image is None:
            return None
        try:
            import io
            from PIL import Image
            raw, _ = view(document["images"][image]["bufferView"])
            return np.asarray(Image.open(io.BytesIO(raw)).convert("RGB"), dtype=np.float64) / 255.0
        except Exception:
            return None

    allVertices, allTriangles, allColors = [], [], []
    count = 0
    for mesh in document.get("meshes", []):
        for primitive in mesh.get("primitives", []):
            if primitive.get("mode", 4) != 4 or "POSITION" not in primitive["attributes"]:
                continue
            attributes = primitive["attributes"]
            vertices = accessor(attributes["POSITION"])[:, :3]
            if "indices" in primitive:
                triangles = accessor(primitive["indices"]).astype(np.int64).reshape(-1, 3)
            else:
                triangles = np.arange(len(vertices)).reshape(-1, 3)
            colors = np.full((len(vertices), 3), 0.7)
            if "COLOR_0" in attributes:
                colors = accessor(attributes["COLOR_0"])[:, :3]
            elif "TEXCOORD_0" in attributes and primitive.get("material") is not None:
                image = texture(document["materials"][primitive["material"]])
                if image is not None:
                    uv = accessor(attributes["TEXCOORD_0"])
                    h, w = image.shape[:2]
                    columns = np.clip((uv[:, 0] % 1.0) * (w - 1), 0, w - 1).astype(np.int64)
                    rows = np.clip((uv[:, 1] % 1.0) * (h - 1), 0, h - 1).astype(np.int64)
                    colors = image[rows, columns]
                factor = document["materials"][primitive["material"]].get("pbrMetallicRoughness", {}).get(
                    "baseColorFactor")
                if factor:
                    colors = colors * np.asarray(factor[:3])
            allVertices.append(vertices)
            allTriangles.append(triangles + count)
            allColors.append(colors)
            count += len(vertices)
    if not allVertices:
        raise AIHeadUnavailable(f"AI head: no triangles in {path!r}")
    return np.concatenate(allVertices), np.concatenate(allTriangles), np.clip(np.concatenate(allColors), 0, 1)


def geometry(vertices: np.ndarray, triangles: np.ndarray, name: str = "aiHead") -> scene3d.GeoData:
    triangles = np.asarray(triangles, dtype=np.int64)
    return scene3d.GeoData(vertices, np.full(len(triangles), 3), triangles.ravel(), name=name)


# Its face

def _render(vertices, triangles, colors, rotation, size=512):
    """ A render (size, size, 3) uint8 of the mesh turned by `rotation` (rows: the mesh axes seen as right, up, toward
    the camera), framed, lit from the camera; and the frame to lift its pixels back (_lift). """
    from .geoRender import rasterize
    center = 0.5 * (vertices.min(0) + vertices.max(0))
    radius = 0.5 * np.linalg.norm(vertices.max(0) - vertices.min(0))
    offset = np.array([0.0, 0.0, -3.0 * radius])
    moved = (vertices - center) @ rotation.T + offset
    camera = face.viewCamera(50.0, size, size)
    xy, depth, _ = camera.project(moved, size, size)
    buffer, ids = rasterize(xy[:, 0], size - xy[:, 1], depth, triangles, (size, size))
    a, b, c = (moved[triangles[:, i]] for i in range(3))
    normals = np.cross(b - a, c - a)
    normals /= np.maximum(np.linalg.norm(normals, axis=1, keepdims=True), 1e-12)
    toCamera = -(a + b + c) / 3.0
    toCamera /= np.maximum(np.linalg.norm(toCamera, axis=1, keepdims=True), 1e-12)
    light = np.abs((normals * toCamera).sum(1))
    triangleColors = colors[triangles].mean(axis=1) * (0.35 + 0.65 * light)[:, None]
    image = np.full((size, size, 3), 0.5)
    covered = ids >= 0
    image[covered] = triangleColors[ids[covered]]
    frame = (camera, center, rotation, offset, size)
    return (np.clip(image, 0, 1) * 255).astype(np.uint8), buffer, frame


def _orientations():
    """ The rotations tried to find the face: its up along each axis, turned around it by quarter turns (the usual
    orientation of the generated meshes, Y up and facing +Z, first). """
    def rotationTo(up, forward):
        up = np.asarray(up, dtype=np.float64)
        forward = np.asarray(forward, dtype=np.float64)
        right = np.cross(up, forward)
        # Rows: the axes of the mesh seen as x (right), y (up), z (toward the camera)
        return np.array([right, up, forward])
    axes = [np.eye(3)[i] * s for i in (1, 2, 0) for s in (1, -1)]
    rotations = []
    for up in axes:
        for forward in axes:
            if abs(np.dot(up, forward)) < 0.5:
                rotations.append(rotationTo(up, forward))
    # Y up facing +Z first
    rotations.sort(key=lambda r: (not np.allclose(r[1], [0, 1, 0]), not np.allclose(r[2], [0, 0, 1])))
    return rotations


def _lift(landmarks, buffer, frame):
    """ The 3D points (mesh space) under the normalized landmarks (x, y in [0, 1], rows from the top) of a render
    (_render), NaN where nothing is seen. """
    camera, center, rotation, offset, size = frame
    columns = np.clip((landmarks[:, 0] * size).astype(np.int64), 0, size - 1)
    rows = np.clip((landmarks[:, 1] * size).astype(np.int64), 0, size - 1)
    depth = buffer[rows, columns]
    seen = np.isfinite(depth)
    points = np.full((len(landmarks), 3), np.nan)
    for index in np.where(seen)[0]:
        origin, direction = camera.ray(landmarks[index, 0] * size, size - landmarks[index, 1] * size, size, size)
        # The depth buffer: the distance along the view axis (-z)
        cameraPoint = origin + depth[index] / max(-direction[2], 1e-9) * direction
        points[index] = (cameraPoint - offset) @ rotation + center
    return points


def findLandmarks(vertices: np.ndarray, triangles: np.ndarray, colors: np.ndarray, detector=None, size: int = 512,
                  cancel=None) -> np.ndarray:
    """
    The 468 MediaPipe face landmarks on a generated head (mesh space, (468, 3); NaN where none): its face found on
    renders of it turned every way, then rendered straight from the front of that face and its landmarks lifted onto
    its surface.
    """
    detector = detector or face.landmarker()
    vertices = np.asarray(vertices, dtype=np.float64)
    triangles = np.asarray(triangles, dtype=np.int64)
    found = None
    for rotation in _orientations():
        if cancel:
            cancel()
        image, buffer, frame = _render(vertices, triangles, colors, rotation, size)
        landmarks, _ = detector.detect(image)
        if landmarks is not None:
            found = _lift(landmarks[:face.MESH_VERTICES], buffer, frame)
            break
    if found is None:
        raise AIHeadUnavailable("AI head: no face found on the generated head.")
    # Again straight from the front of the face found (its landmarks more precise there)
    rotation = _frontRotation(found)
    if rotation is not None:
        image, buffer, frame = _render(vertices, triangles, colors, rotation, size)
        landmarks, _ = detector.detect(image)
        if landmarks is not None:
            front = _lift(landmarks[:face.MESH_VERTICES], buffer, frame)
            if np.isfinite(front).all(1).sum() > 0.8 * face.MESH_VERTICES:
                found = front
    return found


def _frontRotation(landmarks: np.ndarray) -> Optional[np.ndarray]:
    """ The rotation (rows: right, up, toward the camera) looking straight at a face from its landmarks, or None. """
    canonical = face.canonicalFace().vertices[:face.MESH_VERTICES]
    seen = np.isfinite(landmarks).all(1)
    if seen.sum() < 50:
        return None
    _, rotation, _ = similarity(canonical[seen], landmarks[seen])
    # The canonical face looks along +z with y up: its axes in the mesh space, as rows
    return rotation.T


def similarity(source: np.ndarray, target: np.ndarray, weights=None):
    """ (scale, rotation (3, 3), translation): target ~ scale * rotation @ source + translation (Umeyama). """
    source, target = np.asarray(source, dtype=np.float64), np.asarray(target, dtype=np.float64)
    w = np.ones(len(source)) if weights is None else np.asarray(weights, dtype=np.float64)
    w = w / w.sum()
    ms, mt = w @ source, w @ target
    s, t = source - ms, target - mt
    covariance = (t * w[:, None]).T @ s
    u, sigma, vt = np.linalg.svd(covariance)
    d = np.diag([1.0, 1.0, np.sign(np.linalg.det(u @ vt))])
    rotation = u @ d @ vt
    variance = (w * (s ** 2).sum(1)).sum()
    scale = float(np.trace(np.diag(sigma) @ d) / max(variance, 1e-12))
    return scale, rotation, mt - scale * rotation @ ms


def alignment(landmarks: np.ndarray, faceVertices: np.ndarray) -> np.ndarray:
    """ The 4x4 similarity putting a generated head on a face (its landmarks on the 468 vertices of the face; robust:
    the worst ones dropped). """
    seen = np.isfinite(landmarks).all(1)
    weights = seen.astype(np.float64)
    source, target = np.where(seen[:, None], landmarks, 0.0), np.asarray(faceVertices, dtype=np.float64)[:face.MESH_VERTICES]
    for _ in range(4):
        scale, rotation, translation = similarity(source[weights > 0], target[weights > 0], weights[weights > 0])
        error = np.linalg.norm(scale * source @ rotation.T + translation - target, axis=1)
        limit = np.percentile(error[seen], 85)
        weights = (seen & (error <= limit)).astype(np.float64)
    matrix = np.eye(4)
    matrix[:3, :3] = scale * rotation
    matrix[:3, 3] = translation
    return matrix


def transform(points: np.ndarray, matrix: np.ndarray) -> np.ndarray:
    return np.asarray(points, dtype=np.float64) @ matrix[:3, :3].T + matrix[:3, 3]


# The head of the FaceBuilder on it

def _closest(tree, aiVertices, aiNormals, points, normals, maxDistance):
    """ (targets (k, 3), normals (k, 3), valid (k,)): the nearest points of the generated head, valid when near enough
    and facing the same way. """
    distance, index = tree.query(points)
    targets, targetNormals = aiVertices[index], aiNormals[index]
    valid = (distance < maxDistance) & ((targetNormals * normals).sum(1) > 0.3)
    return targets, targetNormals, valid


def vertexNormals(vertices, triangles):
    from .headFit import _vertexNormals
    return _vertexNormals(np.asarray(vertices, dtype=np.float64), np.asarray(triangles, dtype=np.int64))


def registerHead(rest: np.ndarray, topology, aiVertices: np.ndarray, aiTriangles: np.ndarray,
                 landmarks: np.ndarray, iterations: int = 8, maxDistance: float = 2.0, earSmoothing: float = 1.0,
                 cancel=None, progress=None) -> dict:
    """
    The head of the FaceBuilder on a generated head (aligned on it: face space): its face on the landmarks found on it,
    its identity (the proportions of the whole head) and the moves of its ears fitted on the surface of the generated
    head (point to plane on the nearest points: the ears, the upper neck, the face; not the skull, under the hair of the
    generated head), then each ear refined on its own (its vertices to their nearest points, the moves smoothed).

    Returns:
        {"face": (468, 3) list, "identity": [...], "ears": [[x, y, z] right, left], "earOffsets": {vertex: [x, y, z]}}.
    """
    from scipy.spatial import cKDTree
    from . import headFit
    rest = np.asarray(rest, dtype=np.float64)
    aiVertices = np.asarray(aiVertices, dtype=np.float64)
    aiNormals = vertexNormals(aiVertices, aiTriangles)
    tree = cKDTree(aiVertices)
    seen = np.isfinite(landmarks).all(1)
    # The face: the landmarks of the generated head; those not found from the face fitted before (none: the rest)
    faceTarget = np.where(seen[:, None], landmarks, rest[:face.MESH_VERTICES])
    geo = scene3d.GeoData(rest, topology=topology)
    triangles = geo.triangles()
    regions = headFit.headRegions(geo)
    used = regions["ear"] | regions["upperNeck"]
    modes = headFit.identityModel()
    origin = headFit.identityHead(rest, faceTarget, np.zeros(len(modes)))
    jacobian = np.stack([headFit.identityHead(rest, faceTarget, np.eye(len(modes))[k]) - origin
                         for k in range(len(modes))], axis=2)
    earWeights = headFit.earWeights(len(rest))
    earColumns = np.zeros((len(rest), 3, 6))
    for side in range(2):
        for axis in range(3):
            earColumns[:, axis, 3 * side + axis] = earWeights[:, side]
    jacobian = np.concatenate([jacobian, earColumns], axis=2)
    prior = np.r_[np.full(len(modes), 1.0), np.full(6, 0.3)]
    x = np.zeros(jacobian.shape[2])
    indices = np.where(used)[0]
    for iteration in range(iterations):
        if cancel:
            cancel()
        current = origin + jacobian @ x
        normals = headFit._vertexNormals(current, triangles)
        targets, targetNormals, valid = _closest(tree, aiVertices, aiNormals, current[indices], normals[indices],
                                                 maxDistance)
        if valid.sum() < 20:
            break
        k = indices[valid]
        n = targetNormals[valid]
        rows = np.einsum("ij,ijk->ik", n, jacobian[k])
        rhs = ((targets[valid] - current[k]) * n).sum(1)
        # Robust (Cauchy, 5 mm)
        robust = 1.0 / np.sqrt(1.0 + (rhs / 0.5) ** 2)
        rows, rhs = rows * robust[:, None], rhs * robust
        damping = 0.02 * len(k) / 100.0
        lhs = rows.T @ rows + damping * np.diag(prior ** 2)
        step = np.linalg.solve(lhs, rows.T @ rhs - damping * prior ** 2 * x)
        x = x + step
        x[:len(modes)] = np.clip(x[:len(modes)], -headFit.IDENTITY_LIMIT, headFit.IDENTITY_LIMIT)
        if progress:
            progress(0.7 * (iteration + 1) / iterations)
        if np.abs(step).max() < 1e-3:
            break
    head = origin + jacobian @ x
    # Each ear on its own: its vertices to the nearest points (along the normal), the moves smoothed over the ear
    ear = np.where(regions["ear"])[0]
    offsets = np.zeros((len(ear), 3))
    neighbors = cKDTree(rest[ear]).query_ball_point(rest[ear], r=max(earSmoothing, 1e-3))
    normals = headFit._vertexNormals(head, triangles)[ear]
    for _ in range(12):
        if cancel:
            cancel()
        points = head[ear] + offsets
        targets, targetNormals, valid = _closest(tree, aiVertices, aiNormals, points, normals, 1.0)
        wanted = np.where(valid[:, None], ((targets - points) * targetNormals).sum(1)[:, None] * targetNormals, 0.0)
        smoothed = np.array([wanted[group].mean(0) if len(group) else 0.0 for group in neighbors])
        offsets += 0.7 * smoothed
    if progress:
        progress(1.0)
    return {"face": faceTarget.tolist(), "identity": [round(float(v), 5) for v in x[:len(modes)]],
            "ears": [[round(float(v), 4) for v in x[len(modes) + 3 * s:len(modes) + 3 * s + 3]] for s in range(2)],
            "earOffsets": {int(v): [round(float(c), 4) for c in o] for v, o in zip(ear, offsets) if np.abs(o).max() > 1e-4}}


def registeredHead(rest: np.ndarray, registration: dict) -> np.ndarray:
    """ The vertices of the head of a registration (registerHead). """
    from . import headFit
    vertices = headFit.identityHead(rest, np.asarray(registration["face"], dtype=np.float64),
                                    np.asarray(registration["identity"], dtype=np.float64))
    vertices = vertices + headFit.earWeights(len(rest)) @ np.asarray(registration["ears"], dtype=np.float64).reshape(2, 3)
    for vertex, offset in registration.get("earOffsets", {}).items():
        vertices[int(vertex)] += offset
    return vertices
